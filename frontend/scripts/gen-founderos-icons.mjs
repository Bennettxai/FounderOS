// Generates src/lib/founderos/icons/: one wrapper per lucide icon the the operator
// views use, drawn with FounderOS v1's lucide-react 0.441 icon nodes (prod pins
// ^0.441.0; lucide-svelte 0.562 redrew 38 of them). Each wrapper feeds the
// nodes to lucide-svelte's own Icon, so size/strokeWidth/class/color behave
// exactly like the package component.
//
//   node scripts/gen-founderos-icons.mjs <path to lucide-react@0.441 dist/esm/icons>
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { join, resolve } from 'node:path';

const reactIcons = process.argv[2];
if (!reactIcons) throw new Error('usage: gen-founderos-icons.mjs <lucide-react 0.441 dist/esm/icons>');
const root = resolve(import.meta.dirname, '..');
const out = join(root, 'src/lib/founderos/icons');
mkdirSync(out, { recursive: true });

// every name imported from lucide-svelte or the set in the the operator views
// (whole files, so multi-line import blocks count)
const files0 = execSync(
	`grep -rlF -e "from 'lucide-svelte'" -e "from '\\$lib/founderos/icons'" src/lib/founderos "src/routes/(founderos)" || true`,
	{ cwd: root }
)
	.toString()
	.split('\n')
	.filter((f) => f && !f.startsWith('src/lib/founderos/icons/'));
const src = files0.map((f) => readFileSync(join(root, f), 'utf8')).join('\n');
const names = new Set();
for (const m of src.matchAll(/import \{([^}]+)\} from '(?:lucide-svelte|\$lib\/founderos\/icons)'/g)) {
	for (let n of m[1].split(',')) {
		n = n.trim().replace(/\s+as\s+.*/, '');
		if (n && n !== 'Icon' && !n.startsWith('type ')) names.add(n);
	}
}
const kebab = (n) =>
	n
		.replace(/([a-z0-9])([A-Z])/g, '$1-$2')
		.replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
		.toLowerCase()
		.replace(/([a-z])([0-9])/g, '$1-$2');
const files = new Set(readdirSync(reactIcons));
const exports = [];
for (const name of [...names].sort()) {
	const file = kebab(name) + '.js';
	if (!files.has(file)) throw new Error(`lucide-react 0.441 has no ${file} for ${name}`);
	let js = readFileSync(join(reactIcons, file), 'utf8');
	// legacy names are re-exports of the renamed icon (bar-chart-3 -> chart-column)
	const alias = js.match(/export \{ default \} from '\.\/([^']+)'/);
	if (alias) js = readFileSync(join(reactIcons, alias[1]), 'utf8');
	const body = js.match(/createLucideIcon\("([^"]+)", (\[[\s\S]*?\])\);/);
	if (!body) throw new Error(`cannot parse ${file}`);
	// JS object literal -> JSON (keys unquoted), dropping React's `key`
	const nodes = JSON.parse(body[2].replace(/(\w+):/g, '"$1":')).map(([tag, attrs]) => [
		tag,
		Object.fromEntries(Object.entries(attrs).filter(([k]) => k !== 'key'))
	]);
	writeFileSync(
		join(out, `${name}.svelte`),
		`<!-- generated by scripts/gen-founderos-icons.mjs from lucide-react 0.441 (FounderOS v1) -->
<script lang="ts">
	import { Icon } from 'lucide-svelte';
	let props: Record<string, unknown> = $props();
	const iconNode = ${JSON.stringify(nodes)} as [string, Record<string, string>][];
</script>

<Icon name="${kebab(name)}" {...props} {iconNode} />
`
	);
	exports.push(`export { default as ${name} } from './${name}.svelte';`);
}
writeFileSync(
	join(out, 'index.ts'),
	`// generated by scripts/gen-founderos-icons.mjs: FounderOS v1's lucide-react 0.441 glyphs
import type { Component } from 'svelte';
/** Any icon in this set (each takes lucide-svelte's props). */
export type IconComponent = Component<Record<string, unknown>>;
${exports.join('\n')}
`
);
console.log(`${exports.length} icons`);
