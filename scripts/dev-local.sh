# OptimalEngine (Elixir) — starts the live engine the BO server proxies to.
# Skipped silently when:
#   - mix isn't on PATH (no Elixir installed; engine-backed routes return 503)
#   - OPTIMAL_ENGINE_URL isn't set in backend .env (operator opted out)
# When started, the engine listens on :4200 (or whatever port is in the
# OPTIMAL_ENGINE_URL); BO server picks it up automatically because its
# proxy reads OPTIMAL_ENGINE_URL on each request.
ENGINE_LOG="$RUN_DIR/optimal-engine.log"
ENGINE_PID="$RUN_DIR/optimal-engine.pid"
start_engine() {
    if "$CURL" -sf -m 1 "http://127.0.0.1:${ENGINE_PORT:-4200}/api/health" >/dev/null 2>&1; then
        ok "OptimalEngine already running on :${ENGINE_PORT:-4200} - using it"
        return 0
    fi

    local be_env="$ROOT/desktop/backend-go/.env"
    if ! grep -q "^OPTIMAL_ENGINE_URL=" "$be_env" 2>/dev/null; then
        warn "OptimalEngine: OPTIMAL_ENGINE_URL not set in $be_env - skipping"
        return 0
    fi
    if ! command -v mix >/dev/null 2>&1; then
        warn "OptimalEngine: mix not on PATH - install Elixir for engine-backed modules"
        return 0
    fi
    if pid_alive "$ENGINE_PID"; then
        warn "OptimalEngine already running (pid $(cat "$ENGINE_PID"))"
        return 0
    fi
    if "$LSOF" -ti tcp:"$ENGINE_PORT" >/dev/null 2>&1; then
        warn "OptimalEngine: :$ENGINE_PORT already taken (pre-existing process); skipping"
        return 0
    fi
    info "Starting bundled OptimalEngine on :$ENGINE_PORT"
    local engine_dir="$ROOT/optimal-engine"
    if [ ! -d "$engine_dir/deps" ]; then
        info "Fetching OptimalEngine dependencies"
        (cd "$engine_dir" && mix deps.get >>"$ENGINE_LOG" 2>&1)
    fi
    # Defaults to a scratch dir under .run/. To point this install at other
    # engine data, set FOUNDEROS_ENGINE_ROOT / _DB / _CACHE explicitly. The
    # generic OPTIMAL_ENGINE_* variables are deliberately ignored: a shell
    # profile that exports them for another engine must never have this dev
    # stack open (and write into) that engine's data.
    local sw="${FOUNDEROS_ENGINE_ROOT:-$ROOT/.run/optimal-engine-data}"
    local sdb="${FOUNDEROS_ENGINE_DB:-$sw/.optimal/index.db}"
    local scache="${FOUNDEROS_ENGINE_CACHE:-$ROOT/.run/optimal-engine-cache}"
    mkdir -p "$(dirname "$sdb")" "$scache"
    # The engine encrypts connector credentials with CONNECTOR_KEY (64 hex
    # chars) and reports itself down without one once a connector exists.
    # Generate it once per install, next to the engine's data.
    local keyfile="$sw/.optimal/connector_key"
    [ -s "$keyfile" ] || (umask 077; openssl rand -hex 32 > "$keyfile")
    spawn_detached \
        "$ENGINE_PID" \
        "$ENGINE_LOG" \
        "$engine_dir" \
        "CONNECTOR_KEY=${CONNECTOR_KEY:-$(tr -d '[:space:]' < "$keyfile")}" \
        "OPTIMAL_ENGINE_ROOT=$sw" \
        "OPTIMAL_ENGINE_DB=$sdb" \
        "OPTIMAL_ENGINE_CACHE=$scache" \
        "OPTIMAL_API_ENABLED=true" \
        "OPTIMAL_API_PORT=$ENGINE_PORT" \
        -- mix run --no-halt
    for _ in $(seq 1 60); do
        if "$CURL" -sf -m 1 "http://127.0.0.1:$ENGINE_PORT/api/health" >/dev/null 2>&1; then
            ok "OptimalEngine ready on :$ENGINE_PORT"
            return 0
        fi
        sleep 1
    done
    err "OptimalEngine did not become ready in 60s. See $ENGINE_LOG"
    return 1
}

start_frontend() {
    if pid_alive "$RUN_DIR/frontend.pid"; then
        warn "Frontend already running (pid $(cat "$RUN_DIR/frontend.pid"))"
        return
    fi
    info "Starting frontend on :$FRONTEND_PORT"
    spawn_detached "$RUN_DIR/frontend.pid" "$FRONTEND_LOG" "$ROOT/frontend" -- pnpm dev
    for _ in $(seq 1 60); do
        if "$CURL" -sf -m 1 -o /dev/null "http://localhost:$FRONTEND_PORT/"; then
            ok "Frontend serving on :$FRONTEND_PORT"
            return
        fi
        sleep 0.5
    done
    err "Frontend did not respond in 30s — see $FRONTEND_LOG"
    return 1
}

start_electron() {
    if pid_alive "$RUN_DIR/electron.pid"; then
        warn "Electron already running (pid $(cat "$RUN_DIR/electron.pid"))"
        return
    fi
    info "Starting Electron (BUSINESSOS_DEV_URL=http://localhost:$FRONTEND_PORT)"
    # Linux dev: the npm-installed Electron's chrome-sandbox isn't setuid root
    # (only packaged installs get that), so the SUID sandbox aborts at startup.
    # Disable it for the dev instance only — the renderer loads first-party code.
    local sandbox_env=""
    if [ "$(uname -s)" = "Linux" ] && [ ! -u "$ROOT/desktop/node_modules/electron/dist/chrome-sandbox" ]; then
        sandbox_env="ELECTRON_DISABLE_SANDBOX=1"
    fi
    spawn_detached \
        "$RUN_DIR/electron.pid" \
        "$ELECTRON_LOG" \
        "$ROOT/desktop" \
        "BUSINESSOS_DEV_URL=http://localhost:$FRONTEND_PORT" \
        "BUSINESSOS_DEV_PORT=$FRONTEND_PORT" \
        "BUSINESSOS_BACKEND_PORT=$BACKEND_PORT" \
        "OPTIMAL_ENGINE_URL=${OPTIMAL_ENGINE_URL:-http://127.0.0.1:$ENGINE_PORT}" \
        ${sandbox_env:+"$sandbox_env"} \
        -- ./node_modules/.bin/electron .
    for _ in $(seq 1 40); do
        if grep -q "Loading from http://localhost:$FRONTEND_PORT" "$ELECTRON_LOG" 2>/dev/null; then
            ok "Electron launched"
            return
        fi
        if ! pid_alive "$RUN_DIR/electron.pid"; then
            err "Electron exited prematurely — see $ELECTRON_LOG"
            return 1
        fi
        sleep 0.5
    done
    warn "Electron didn't report ready in 20s; still running, check $ELECTRON_LOG"
}

cmd_start() {
    ensure_backend_env
    sync_env_files
    ensure_local_postgres
    ensure_local_redis
    ensure_frontend_deps
    ensure_desktop_deps
    build_backend_if_stale
    build_desktop_if_stale
    if [ "$BACKEND_REBUILT" = "1" ] && pid_alive "$RUN_DIR/backend.pid"; then
        info "Restarting managed backend to activate the new binary"
        stop_one backend
    fi
    if [ "$DESKTOP_REBUILT" = "1" ] && pid_alive "$RUN_DIR/electron.pid"; then
        info "Restarting Electron to activate the new bundles"
        stop_one electron
    fi
    # The backend owns the migration ledger. Running an individual migration
    # here records a partial ledger and prevents the backend from safely
    # baselining an existing local database on first startup.
    start_engine
    start_backend
    verify_schema_contract
    start_frontend
    if [ "${BUSINESSOS_HEADLESS:-0}" = "1" ]; then
        info "Headless mode enabled - skipping Electron launch"
    else
        start_electron
    fi
    echo
    cmd_status
    echo
    echo "Logs:    make dev-local-logs    (or: tail -f $RUN_DIR/*.log)"
    echo "Stop:    make dev-local-stop"
}

stop_one() {
    local name="$1" pid_file="$RUN_DIR/$1.pid"
    if [ -f "$pid_file" ]; then
        local pid; pid=$(cat "$pid_file")
        if kill -0 "$pid" 2>/dev/null; then
            pkill -P "$pid" 2>/dev/null || true
            kill "$pid" 2>/dev/null || true
            for _ in $(seq 1 20); do
                kill -0 "$pid" 2>/dev/null || break
                sleep 0.1
            done
            if kill -0 "$pid" 2>/dev/null; then
                kill -KILL "$pid" 2>/dev/null || true
            fi
            ok "stopped $name (pid $pid)"
        fi
        rm -f "$pid_file"
    fi
}

cmd_stop() {
    info "Stopping local dev stack"
    stop_one electron
    stop_one frontend
    stop_one backend
    stop_one optimal-engine
    if pid_alive "$RUN_DIR/redis.pid"; then
        stop_one redis
    fi
    local data_dir="${BUSINESSOS_PGDATA:-$RUN_DIR/pgdata}" pg_bin
    if [ -f "$data_dir/PG_VERSION" ] && pg_bin=$(resolve_postgres_bin "$(cat "$data_dir/PG_VERSION")"); then
        "$pg_bin/pg_ctl" -D "$data_dir" status >/dev/null 2>&1 && \
            "$pg_bin/pg_ctl" -D "$data_dir" stop -m fast >/dev/null
    fi
    pkill -f "$ROOT/desktop/node_modules/electron/dist/Electron.app/Contents/MacOS/Electron" 2>/dev/null || true
    pkill -f "electron-forge" 2>/dev/null || true
    pkill -f "BusinessOS.app" 2>/dev/null || true
    ok "Stack stopped"
}

cmd_status() {
    local be_env="$ROOT/desktop/backend-go/.env"
    local status_postgres_port="$POSTGRES_PORT"
    local status_redis_port="$REDIS_PORT"
    local configured_url
    configured_url=$(read_env_value DATABASE_URL "$be_env")
    [ -z "$configured_url" ] || status_postgres_port=$(url_port "$configured_url" 5432)
    configured_url=$(read_env_value REDIS_URL "$be_env")
    [ -z "$configured_url" ] || status_redis_port=$(url_port "$configured_url" 6379)

    printf '%-10s %-7s %-12s %s\n' "Service" "Port" "Status" "PID"
    printf '%-10s %-7s %-12s %s\n' "-------" "----" "------" "---"
    for row in "postgres:$status_postgres_port" "redis:$status_redis_port" "optimal-engine:$ENGINE_PORT" "backend:$BACKEND_PORT" "frontend:$FRONTEND_PORT" "electron:-"; do
        name="${row%%:*}"
        port="${row##*:}"
        if [ "$name" = "postgres" ] && { pg_bin=$(resolve_postgres_bin "$(cat "$RUN_DIR/pgdata/PG_VERSION" 2>/dev/null)" 2>/dev/null); } && "$pg_bin/pg_isready" -h 127.0.0.1 -p "$status_postgres_port" >/dev/null 2>&1; then
            status="$(color '32' 'running')"
            pid="managed"
        elif [ "$name" = "redis" ] && [ -n "$REDIS_CLI" ] && "$REDIS_CLI" -h 127.0.0.1 -p "$status_redis_port" ping >/dev/null 2>&1; then
            status="$(color '32' 'running')"
            pid="$(pid_for redis)"
            [ "$pid" != "-" ] || pid="external"
        elif [ "$name" = "optimal-engine" ] && "$CURL" -sf -m 1 "http://127.0.0.1:$ENGINE_PORT/api/health" >/dev/null 2>&1; then
            status="$(color '32' 'running')"
            pid="$(pid_for optimal-engine)"
            [ "$pid" != "-" ] || pid="external"
        elif pid_alive "$RUN_DIR/$name.pid"; then
            status="$(color '32' 'running')"
            pid=$(cat "$RUN_DIR/$name.pid")
        else
            status="$(color '31' 'down')"
            pid="-"
        fi
        printf '%-10s %-7s %-22s %s\n' "$name" "$port" "$status" "$pid"
    done
}

cmd_verify() {
    ensure_backend_env
    ensure_local_postgres
    ensure_local_redis

    info "Checking backend readiness"
    "$CURL" -fsS -m 5 "http://localhost:$BACKEND_PORT/readyz" >/dev/null
    ok "Backend is ready with database and Redis"

    verify_schema_contract

    info "Checking frontend"
    "$CURL" -fsS -m 5 "http://localhost:$FRONTEND_PORT/" >/dev/null
    ok "Frontend is reachable"

    if [ "${BUSINESSOS_HEADLESS:-0}" != "1" ] && ! pid_alive "$RUN_DIR/electron.pid"; then
        err "Electron is not running. Run: make dev-local-restart"
        return 1
    fi
    if [ "${BUSINESSOS_HEADLESS:-0}" != "1" ]; then
        ok "Electron process is running"
    fi

    if ! "$CURL" -fsS -m 5 "http://127.0.0.1:$ENGINE_PORT/api/health" >/dev/null; then
        err "Optimal Engine is unavailable on :$ENGINE_PORT"
        return 1
    fi
    ok "Optimal Engine is reachable"
}

cmd_logs() {
    exec tail -F "$BACKEND_LOG" "$FRONTEND_LOG" "$ELECTRON_LOG" 2>/dev/null
}

main() {
    case "${1:-start}" in
        start)          cmd_start ;;
        stop)           cmd_stop ;;
        restart)        cmd_stop; sleep 1; cmd_start ;;
        status)         cmd_status ;;
        logs)           cmd_logs ;;
        verify)         cmd_verify ;;
        *) echo "Usage: $0 {start|stop|restart|status|verify|logs}"; exit 1 ;;
    esac
}

if [ "${BASH_SOURCE[0]}" = "$0" ]; then
    main "$@"
fi
